/**
 * Helper to zero-pad numbers
 */
function pad2(n: number): string {
  return n < 10 ? `0${n}` : `${n}`;
}

/**
 * Computes the date string "YYYY-MM-DD" for a festival in a given year.
 */
export function getFestivalDateForYear(festival: Festival, year: number): string | null {
  if (festival.isSolarFixed && festival.fixedMonth && festival.fixedDay) {
    return `${year}-${pad2(festival.fixedMonth)}-${pad2(festival.fixedDay)}`;
  }

  const multiYear = MULTI_YEAR_FESTIVAL_DATES[festival.id];
  if (multiYear && multiYear[year]) {
    return multiYear[year];
  }

  // Fallback for years beyond pre-computed lookup
  const approxMonth = festival.fixedMonth || festival.monthNumber;
  return `${year}-${pad2(approxMonth)}-15`;
}

/**
 * Returns all festival events for a specific year, sorted by date.
 */
export function getAllFestivalsForYear(year: number): FestivalEvent[] {
  const events: FestivalEvent[] = [];

  for (const f of MASTER_FESTIVALS) {
    const dateStr = getFestivalDateForYear(f, year);
    if (!dateStr) continue;

    const [y, m, d] = dateStr.split("-").map(Number);
    events.push({
      id: `${f.id}-${year}`,
      name: f.name,
      category: f.category,
      monthHindi: f.monthHindi,
      dateStr,
      year: y,
      month: m,
      day: d,
      greeting: f.greeting || `पावन पर्व ${f.name} की आप सभी को हार्दिक शुभकामनाएं!`,
      description: f.description || `${f.name} (${f.category})`,
      icon: f.icon || "🪔",
    });
  }

  return events.sort((a, b) => a.dateStr.localeCompare(b.dateStr));
}

/**
 * Formats a Date object into "YYYY-MM-DD" local time string.
 */
export function formatLocalDateStr(d: Date): string {
  const y = d.getFullYear();
  const m = pad2(d.getMonth() + 1);
  const day = pad2(d.getDate());
  return `${y}-${m}-${day}`;
}

/**
 * Formats date into readable Hindi format e.g. "04 सितंबर 2026"
 */
export function formatHindiDate(dateStr: string): string {
  const parts = dateStr.split("-");
  if (parts.length !== 3) return dateStr;
  const day = parseInt(parts[2], 10);
  const monthIdx = parseInt(parts[1], 10);
  const year = parts[0];

  const hindiMonths = [
    "",
    "जनवरी",
    "फरवरी",
    "मार्च",
    "अप्रैल",
    "मई",
    "जून",
    "जुलाई",
    "अगस्त",
    "सितंबर",
    "अक्टूबर",
    "नवंबर",
    "दिसंबर",
  ];

  return `${pad2(day)} ${hindiMonths[monthIdx] || ""} ${year}`;
}

/**
 * Get festivals happening TODAY (from 00:00 to 23:59:59).
 */
export function getTodayFestivals(currentDate: Date = new Date()): FestivalEvent[] {
  const todayStr = formatLocalDateStr(currentDate);
  const year = currentDate.getFullYear();
  const yearFestivals = getAllFestivalsForYear(year);

  return yearFestivals.filter((ev) => ev.dateStr === todayStr);
}

/**
 * Get upcoming festivals from today onwards (up to limit).
 */
export function getUpcomingFestivals(
  currentDate: Date = new Date(),
  limit: number = 10
): FestivalEvent[] {
  const todayStr = formatLocalDateStr(currentDate);
  const currentYear = currentDate.getFullYear();

  // Load current year and next year to handle year-boundary smoothly
  const allEvents = [
    ...getAllFestivalsForYear(currentYear),
    ...getAllFestivalsForYear(currentYear + 1),
  ];

  const upcoming = allEvents.filter((ev) => ev.dateStr >= todayStr);
  return upcoming.slice(0, limit);
}
